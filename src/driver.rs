//! The generated driver crate: render, build with a repair loop, and run one call.
//!
//! Discovery cannot compile, so some callable the parser accepted will still fail to compile
//! in the driver (a `Result` whose error type is not `Debug`, a wrapper nesting the lowering
//! did not expect). The repair loop is what turns that from a broken scan into a skip list:
//! build, attribute every compiler error that points into the generated `calls.rs` to the
//! target whose generated block it sits in, drop that target, rebuild. A target the compiler
//! refuses is reported as `unconstructible-parameter` by `prepare`, which is the honest
//! reason: the driver cannot build a call for it.
//!
//! The driver runs one call per process. The child is spawned in its own process group and
//! killed at the deadline, so a hung target dies with the invocation instead of taking the
//! plugin with it; a panic is caught, and its message and source location are the fault
//! frame. Coverage is the LLVM instrumentation runtime's buffer, dumped to a file named by
//! `AFZ_DRIVER_PROFRAW` before the result line is printed.

use std::io::Write as _;
use std::ops::Range;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

use afz_protocol::{ValueNode, ValueTree};

use crate::discover::{Inventory, RetShape, Tgt};
use crate::lower::{Build, PassMode, Wrap};

/// How many repair rounds before the build is declared hopeless. Every round drops at least
/// one target, so a scan with more broken targets than this gets a hard error rather than a
/// silently truncated inventory.
const MAX_REPAIR_ROUNDS: usize = 40;

/// The line span of every target's generated block, keyed by target id: the map a compiler
/// error line becomes a dropped target through.
type TargetSpans = Vec<(String, Range<usize>)>;

/// The generated driver crate's directory under the scan root. `.autofuzz` is skipped by discovery,
/// so a re-discover never parses the driver as a package.
pub fn driver_dir(root: &Path) -> PathBuf {
    root.join(".autofuzz").join("driver")
}

/// The built driver, with the targets the compiler refused.
pub struct Driver {
    pub dir: PathBuf,
    pub bin: PathBuf,
    pub profiles: PathBuf,
    /// Target ids the repair loop dropped. `prepare` skips them; `invoke` rejects them.
    pub dropped: Vec<String>,
    pub bin_exists: bool,
}

/// One render of the driver sources. Returns the layout and the line span of every target's
/// generated block, which is how a compiler error line becomes a dropped target.
fn render(inventory: &Inventory, dropped: &[String]) -> Result<(Driver, TargetSpans), String> {
    let dir = driver_dir(&inventory.root);
    let src = dir.join("src");
    std::fs::create_dir_all(&src).map_err(|e| format!("cannot create {}: {e}", src.display()))?;
    let profiles = dir.join("profiles");
    std::fs::create_dir_all(&profiles).map_err(|e| format!("cannot create {}: {e}", profiles.display()))?;

    std::fs::write(dir.join("Cargo.toml"), cargo_toml(inventory)).map_err(|e| format!("cannot write Cargo.toml: {e}"))?;
    std::fs::write(src.join("main.rs"), DRIVER_MAIN).map_err(|e| format!("cannot write main.rs: {e}"))?;
    std::fs::write(src.join("afzrt.rs"), AFZRT).map_err(|e| format!("cannot write afzrt.rs: {e}"))?;
    let (calls, spans) = calls_rs(inventory, dropped);
    std::fs::write(src.join("calls.rs"), calls).map_err(|e| format!("cannot write calls.rs: {e}"))?;

    let bin = dir.join("target").join("debug").join("afz-rust-driver");
    let bin_exists = bin.is_file();
    Ok((Driver { dir, bin, profiles, dropped: Vec::new(), bin_exists }, spans))
}

fn cargo_toml(inventory: &Inventory) -> String {
    let mut out = String::from("[package]\nname = \"afz-rust-driver\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n[dependencies]\nserde_json = \"1\"\n");
    for package in &inventory.packages {
        out.push_str(&format!("{} = {{ path = \"{}\" }}\n", package.manifest_name, package.root.display()));
    }
    // Standalone: the driver is never a member of the scanned workspace. The table goes
    // last so the path dependencies stay inside `[dependencies]`.
    out.push_str("\n[workspace]\n");
    out
}

/// The generated `calls.rs`. Each target's block is delimited by a `// target <id>` marker so
/// a compiler error line maps back to the target that caused it.
fn calls_rs(inventory: &Inventory, dropped: &[String]) -> (String, TargetSpans) {
    let mut out = String::from(
        "// Generated by afz-rust. One function per discovered call; `dispatch` selects by the\n\
         // full Rust path discovery recorded.\n\
         #![allow(unused_mut, unused_variables)]\n\
         use ::serde_json::{json, Value};\n\
         use crate::afzrt::R;\n\n",
    );
    let mut arms = String::new();
    let mut spans: TargetSpans = Vec::new();
    let mut index = 0usize;
    for tgt in &inventory.targets {
        if dropped.iter().any(|d| d == &tgt.id) {
            continue;
        }
        let func = format!("call_{index}");
        index += 1;
        let start = out.matches('\n').count() + 1;
        out.push_str(&format!("// target {}\n{}\n\n", tgt.id, call_body(tgt, &func)));
        spans.push((tgt.id.clone(), start..out.matches('\n').count() + 1));
        arms.push_str(&format!("    \"{}\" => {func}(a),\n", tgt.call_path));
    }
    out.push_str(&format!(
        "pub fn dispatch(name: &str, a: &[Value]) -> R<Value> {{\n    match name {{\n{arms}        _ => Err(format!(\"the driver has no call named {{name}}\")),\n    }}\n}}\n"
    ));
    (out, spans)
}

/// One target's generated function: build every parameter from its JSON value, call, and map
/// the return shape onto the response statuses.
fn call_body(tgt: &Tgt, func: &str) -> String {
    let mut out = format!("fn {func}(a: &[Value]) -> R<Value> {{\n");
    out.push_str(&format!("    if a.len() != {} {{ return Err(format!(\"{} takes {} arguments, got {{}}\", a.len())); }}\n", tgt.params.len(), tgt.call_path, tgt.params.len()));
    for (index, param) in tgt.params.iter().enumerate() {
        let built = build_expr(&param.build, &format!("&a[{index}]"), 1);
        let ty = binding_type(&param.wrap, &param.build);
        // `Cow<'static, str>` is built from a `String`: the written parameter type is the
        // binding type and `Cow::Owned` fills it.
        let expr = match &param.wrap {
            Wrap::None => built,
            Wrap::Boxed => format!("::std::boxed::Box::new({built})"),
            Wrap::BoxedSlice => format!("({built}).into_boxed_slice()"),
            Wrap::Arced => format!("::std::sync::Arc::new({built})"),
            Wrap::Rced => format!("::std::rc::Rc::new({built})"),
            Wrap::Cowed(_) => format!("::std::borrow::Cow::Owned({built})"),
        };
        out.push_str(&format!("    let mut a{index}: {ty} = {expr};\n"));
    }
    let arguments: Vec<String> = tgt
        .params
        .iter()
        .enumerate()
        .map(|(index, param)| pass_expression(&PassModeSnapshot { mode: param.mode, receiver: param.receiver }, index))
        .collect();
    let call = format!("{}({})", tgt.call_path, arguments.join(", "));
    let call = if tgt.unsafe_call { format!("unsafe {{ {call} }}") } else { call };
    let mapped = match (tgt.ret, tgt.returns_value) {
        (RetShape::Plain, true) => format!(
            "let __r = {call};\n    Ok(json!({{\"status\": \"returned\", \"value\": ::serde_json::to_value(&__r).unwrap_or(Value::Null)}}))"
        ),
        (RetShape::Plain, false) => format!("let __r = {call};\n    let _ = &__r;\n    Ok(json!({{\"status\": \"returned\"}}))"),
        (RetShape::Result, true) => format!(
            "let __r = {call};\n    Ok(match __r {{ ::std::result::Result::Ok(__v) => json!({{\"status\": \"returned\", \"value\": ::serde_json::to_value(&__v).unwrap_or(Value::Null)}}), ::std::result::Result::Err(__e) => json!({{\"status\": \"returned-err\", \"display\": format!(\"{{__e:?}}\")}}) }})"
        ),
        (RetShape::Result, false) => format!(
            "let __r = {call};\n    Ok(match __r {{ ::std::result::Result::Ok(__v) => {{ let _ = &__v; json!({{\"status\": \"returned\"}}) }}, ::std::result::Result::Err(__e) => json!({{\"status\": \"returned-err\", \"display\": format!(\"{{__e:?}}\")}}) }})"
        ),
        (RetShape::Option, true) => format!(
            "let __r = {call};\n    Ok(match __r {{ ::std::option::Option::Some(__v) => json!({{\"status\": \"returned\", \"value\": ::serde_json::to_value(&__v).unwrap_or(Value::Null)}}), ::std::option::Option::None => json!({{\"status\": \"returned-none\"}}) }})"
        ),
        (RetShape::Option, false) => format!(
            "let __r = {call};\n    Ok(match __r {{ ::std::option::Option::Some(__v) => {{ let _ = &__v; json!({{\"status\": \"returned\"}}) }}, ::std::option::Option::None => json!({{\"status\": \"returned-none\"}}) }})"
        ),
    };
    out.push_str(&format!("    {mapped}\n}}"));
    out
}

/// The pass mode and receiver kind of one parameter, enough to render the call argument.
/// The reproducer renders the same expressions the driver compiles.
pub struct PassModeSnapshot {
    pub mode: PassMode,
    pub receiver: crate::discover::ReceiverKind,
}

/// How a built parameter reaches the call.
pub fn pass_expression(param: &PassModeSnapshot, index: usize) -> String {
    use crate::discover::ReceiverKind;
    match param.receiver {
        ReceiverKind::None => match param.mode {
            PassMode::Value => format!("a{index}"),
            PassMode::Ref => format!("&a{index}"),
            PassMode::RefMut => format!("&mut a{index}"),
        },
        ReceiverKind::Value => format!("a{index}"),
        ReceiverKind::Ref => format!("&a{index}"),
        ReceiverKind::RefMut => format!("&mut a{index}"),
    }
}

/// The binding type for a built parameter: the wrapper's own type, or the lowered type.
pub fn binding_type(wrap: &Wrap, build: &Build) -> String {
    match wrap {
        Wrap::None => build.rust_ty(),
        Wrap::Boxed => format!("::std::boxed::Box<{}>", build.rust_ty()),
        Wrap::BoxedSlice => format!("::std::boxed::Box<[{}]>", build.rust_ty()),
        Wrap::Arced => format!("::std::sync::Arc<{}>", build.rust_ty()),
        Wrap::Rced => format!("::std::rc::Rc<{}>", build.rust_ty()),
        Wrap::Cowed(written) => written.clone(),
    }
}


/// The Rust expression that builds one value from a `&Value`. Containers, objects, and enums
/// become immediately-invoked closures so `?` and early `return` work at any nesting depth.
fn build_expr(build: &Build, accessor: &str, depth: usize) -> String {
    let pad = "    ".repeat(depth + 1);
    let inner = |build: &Build, accessor: &str| build_expr(build, accessor, depth + 1);
    match build {
        Build::Bool => format!("crate::afzrt::b_of({accessor})?"),
        Build::Int(t) => {
            if t.starts_with('u') {
                format!("crate::afzrt::u_of({accessor})? as {t}")
            } else {
                format!("crate::afzrt::i_of({accessor})? as {t}")
            }
        }
        Build::Float(t) => format!("crate::afzrt::f_of({accessor})? as {t}"),
        Build::Char => format!("crate::afzrt::c_of({accessor})?"),
        Build::Str => format!("crate::afzrt::s_of({accessor})?"),
        Build::PathBuf => format!("::std::path::PathBuf::from(crate::afzrt::s_of({accessor})?)"),
        Build::JsonValue => format!("{accessor}.clone()"),
        Build::Vec { inner: element } => format!(
            "(|__v: &Value| -> R<{}> {{\n{pad}    let __arr = crate::afzrt::arr_of(__v)?;\n{pad}    let mut __out = ::std::vec::Vec::with_capacity(__arr.len());\n{pad}    for __item in __arr {{ __out.push({}); }}\n{pad}    Ok(__out)\n{pad}}})({accessor})?",
            build.rust_ty(),
            inner(element, "&__item")
        ),
        Build::Set { inner: element, ordered } => {
            let set = if *ordered { "::std::collections::BTreeSet" } else { "::std::collections::HashSet" };
            format!(
                "(|__v: &Value| -> R<{}> {{\n{pad}    let mut __out: {set}<{}> = {set}::new();\n{pad}    for __item in crate::afzrt::arr_of(__v)? {{ __out.insert({}); }}\n{pad}    Ok(__out)\n{pad}}})({accessor})?",
                build.rust_ty(),
                element.rust_ty(),
                inner(element, "&__item")
            )
        }
        Build::Map { value, ordered } => {
            let map = if *ordered { "::std::collections::BTreeMap" } else { "::std::collections::HashMap" };
            format!(
                "(|__v: &Value| -> R<{}> {{\n{pad}    let mut __out: {map}<::std::string::String, {}> = {map}::new();\n{pad}    for (__key, __item) in crate::afzrt::entries_of(__v)? {{ __out.insert(__key, {}); }}\n{pad}    Ok(__out)\n{pad}}})({accessor})?",
                build.rust_ty(),
                value.rust_ty(),
                inner(value, "&__item")
            )
        }
        Build::Tuple { items } => {
            let count = items.len();
            let parts: Vec<String> =
                items.iter().enumerate().map(|(index, item)| inner(item, &format!("&__arr[{index}]"))).collect();
            let check = if count == 0 {
                "if !__arr.is_empty() { return Err(\"expected () as an empty JSON array\".into()); }".to_string()
            } else {
                format!(
                    "if __arr.len() != {count} {{ return Err(format!(\"expected a JSON array of {count} items, got {{}}\", __arr.len())); }}"
                )
            };
            format!(
                "(|__v: &Value| -> R<{}> {{\n{pad}    let __arr = crate::afzrt::arr_of(__v)?;\n{pad}    {check}\n{pad}    Ok(({},))\n{pad}}})({accessor})?",
                build.rust_ty(),
                parts.join(", ")
            )
        }
        Build::Option { inner: element } => format!(
            "(|__v: &Value| -> R<{}> {{\n{pad}    if __v.is_null() {{ return Ok(None); }}\n{pad}    Ok(Some({}))\n{pad}}})({accessor})?",
            build.rust_ty(),
            inner(element, "__v")
        ),
        Build::Struct { path, fields } => {
            let parts: Vec<String> = fields
                .iter()
                .map(|(name, field)| format!("{name}: {}", inner(field, &format!("crate::afzrt::field(&__o, {name:?})?"))))
                .collect();
            format!(
                "(|__v: &Value| -> R<{path}> {{\n{pad}    let __o = crate::afzrt::obj_of(__v)?;\n{pad}    Ok({path} {{ {}, }})\n{pad}}})({accessor})?",
                parts.join(", ")
            )
        }
        Build::Enum { path, variants } => {
            let mut out = String::from(&format!(
                "(|__v: &Value| -> R<{path}> {{\n{pad}    if let Some(__s) = __v.as_str() {{\n{pad}        return match __s {{"
            ) as &str);
            let units: Vec<&crate::lower::Variant> =
                variants.iter().filter(|v| matches!(v.shape, crate::lower::VariantShape::Unit)).collect();
            if units.is_empty() {
                out.push_str(&format!(" _ => Err(format!(\"{{__s}} is not a variant of {path}\")),"));
            } else {
                for unit in &units {
                    out.push_str(&format!(" \"{}\" => Ok({path}::{}),", unit.name, unit.name));
                }
                out.push_str(&format!(" _ => Err(format!(\"{{__s}} is not a unit variant of {path}\")),"));
            }
            out.push_str(&format!("\n{pad}        }}\n{pad}    }}"));
            for variant in variants {
                match &variant.shape {
                    crate::lower::VariantShape::Unit => {}
                    crate::lower::VariantShape::Tuple(items) => {
                        let parts: Vec<String> = items
                            .iter()
                            .enumerate()
                            .map(|(index, item)| inner(item, &format!("&__arr[{index}]")))
                            .collect();
                        out.push_str(&format!(
                            "\n{pad}    if let Some(__arr) = __v.as_array() {{ if __arr.len() == {} {{ if let Ok(__built) = (|__arr: &[Value]| -> R<{path}> {{ Ok({path}::{}({},)) }})(__arr) {{ return Ok(__built); }} }} }}",
                            items.len(),
                            variant.name,
                            parts.join(", ")
                        ));
                    }
                    crate::lower::VariantShape::Struct(fields) => {
                        let parts: Vec<String> = fields
                            .iter()
                            .map(|(name, field)| {
                                format!("{name}: {}", inner(field, &format!("crate::afzrt::field(&__o, {name:?})?")))
                            })
                            .collect();
                        out.push_str(&format!(
                            "\n{pad}    if let Some(__o) = __v.as_object() {{ if let Ok(__built) = (|__o: &::serde_json::Map<::std::string::String, Value>| -> R<{path}> {{ Ok({path}::{} {{ {}, }}) }})(__o) {{ return Ok(__built); }} }}",
                            variant.name,
                            parts.join(", ")
                        ));
                    }
                }
            }
            out.push_str(&format!("\n{pad}    Err(format!(\"no variant of {path} matches {{}}\", __v))\n{pad}}})({accessor})?"));
            out
        }
    }
}

/// Build the driver, dropping the targets whose generated code the compiler refuses, until
/// the crate compiles.
pub fn build(inventory: &Inventory) -> Result<Driver, String> {
    let mut dropped: Vec<String> = Vec::new();
    let mut last_stderr = String::new();
    for _round in 0..=MAX_REPAIR_ROUNDS {
        let (mut driver, spans) = render(inventory, &dropped)?;
        match cargo_build(&driver) {
            Ok(()) => {
                driver.dropped = dropped;
                driver.bin_exists = driver.bin.is_file();
                return Ok(driver);
            }
            Err(stderr) => {
                last_stderr = stderr;
                let blamed = blamed_targets(&spans, &last_stderr);
                let errors: String = last_stderr
                    .lines()
                    .filter(|line| line.starts_with("error") || (line.contains("-->") && !line.contains("warning")))
                    .collect::<Vec<_>>()
                    .join("\n");
                eprintln!("driver build failed, blamed {} target(s):\n{errors}", blamed.len());
                for id in blamed {
                    if !dropped.contains(&id) {
                        eprintln!("dropped {id}: the driver did not compile it");
                        dropped.push(id);
                    }
                }
            }
        }
    }
    Err(format!("the driver needed more than {MAX_REPAIR_ROUNDS} repair rounds; last errors:\n{}", tail(&last_stderr, 2000)))
}

/// The `cargo build` of the rendered crate: offline first (the registry cache is the normal
/// path), online as the fallback, always instrumented so the coverage buffer exists.
fn cargo_build(driver: &Driver) -> Result<(), String> {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
    let run = |offline: bool| -> Result<(), String> {
        let mut command = Command::new(&cargo);
        command.arg("build").arg("--bin").arg("afz-rust-driver").current_dir(&driver.dir).env("RUSTFLAGS", "-Cinstrument-coverage").env("CARGO_TERM_COLOR", "never");
        if offline {
            command.arg("--offline");
        }
        let output = command.output().map_err(|e| format!("{cargo} did not start: {e}"))?;
        if output.status.success() {
            Ok(())
        } else {
            Err(String::from_utf8_lossy(&output.stderr).into_owned())
        }
    };
    match run(true) {
        Ok(()) => Ok(()),
        Err(offline) => run(false).map_err(|online| {
            // A compile error is the same offline and online; the online stderr is the fuller
            // text only when offline failed for a registry reason.
            if offline.contains("--offline") || offline.contains("offline") || offline.contains("registry") {
                format!("{online}\n(the offline attempt failed first: {})", tail(&offline, 600))
            } else {
                offline
            }
        }),
    }
}

/// Every target whose generated block contains a line a compiler error pointed at.
fn blamed_targets(spans: &[(String, Range<usize>)], stderr: &str) -> Vec<String> {
    let mut out = Vec::new();
    // A `-->` position belongs to the diagnostic header above it. Only errors may drop a
    // target: every generated call carries warnings, and blaming those drops the whole crate.
    let mut in_error = false;
    for line in stderr.lines() {
        let line = line.trim();
        if line.starts_with("error") {
            in_error = true;
            continue;
        }
        if line.starts_with("warning") || line.starts_with("note") || line.starts_with("help") {
            in_error = false;
            continue;
        }
        if !in_error {
            continue;
        }
        let Some(rest) = line.strip_prefix("-->") else { continue };
        let Some((path, rest)) = rest.split_once(':') else { continue };
        if !path.ends_with("src/calls.rs") {
            continue;
        }
        let Ok(line_number) = rest.split(':').next().unwrap_or("").parse::<usize>() else { continue };
        for (id, span) in spans {
            if span.contains(&line_number) && !out.contains(id) {
                out.push(id.clone());
            }
        }
    }
    out
}

fn tail(text: &str, limit: usize) -> String {
    if text.len() <= limit {
        return text.to_string();
    }
    let mut cut = text.len() - limit;
    while !text.is_char_boundary(cut) {
        cut += 1;
    }
    text[cut..].to_string()
}

/// What one driver run ended as.
pub enum Run {
    /// The child answered with the result JSON.
    Answered(serde_json::Value),
    /// The child exited or died without a result line: the string is the exit description
    /// plus the stderr tail.
    Silent(String),
    /// The deadline cut the call; the child was killed.
    Deadline,
}

/// Build one reproducer binary of the driver crate. The same `RUSTFLAGS` as the scan build
/// reuse the compiled dependency graph, so only the new binary is compiled. An `Err` carries
/// the compiler's stderr; the caller drops the file and falls back to the paste-in header.
pub fn build_repro(dir: &Path, bin: &str) -> Result<(), String> {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
    let output = Command::new(&cargo)
        .arg("build")
        .arg("--offline")
        .arg("--bin")
        .arg(bin)
        .current_dir(dir)
        .env("RUSTFLAGS", "-Cinstrument-coverage")
        .env("CARGO_TERM_COLOR", "never")
        .output()
        .map_err(|e| format!("{cargo} did not start: {e}"))?;
    if output.status.success() {
        Ok(())
    } else {
        Err(String::from_utf8_lossy(&output.stderr).into_owned())
    }
}

/// Run one call in a fresh driver child. The child gets its own process group so a kill takes
/// everything it spawned with it; `profraw` names the file the coverage buffer goes to.
pub fn run(driver: &Driver, tgt: &Tgt, args: Vec<serde_json::Value>, deadline: Duration, profraw: Option<&Path>) -> (Run, Duration) {
    let started = Instant::now();
    let request = serde_json::json!({ "call": tgt.call_path, "args": args });
    let mut command = Command::new(&driver.bin);
    command.stdin(Stdio::piped()).stdout(Stdio::piped()).stderr(Stdio::piped());
    // An instrumented child whose `LLVM_PROFILE_FILE` is unset dumps the runtime's fallback
    // `default_*.profraw` into its working directory, which is wherever the scan left it.
    // Point the runtime at the invocation's own file and run the child in the profiles
    // directory, so every profile write lands where the plugin reads and cleans up.
    command.current_dir(&driver.profiles);
    match profraw {
        Some(path) => {
            command.env("AFZ_DRIVER_PROFRAW", path);
            command.env("LLVM_PROFILE_FILE", path);
        }
        None => {
            command.env("AFZ_DRIVER_PROFRAW", "");
            command.env("LLVM_PROFILE_FILE", ::std::path::Path::new(&driver.profiles).join("discarded.profraw"));
        }
    }
    #[cfg(unix)]
    {
        use std::os::unix::process::CommandExt as _;
        command.process_group(0);
    }
    let Ok(mut child) = command.spawn() else {
        return (Run::Silent(format!("the driver child {} did not start", driver.bin.display())), started.elapsed());
    };
    if let Some(mut stdin) = child.stdin.take() {
        let _ = stdin.write_all(request.to_string().as_bytes());
        // Closing stdin here: the child reads to EOF before calling.
    }
    let cut = started + deadline;
    loop {
        match child.try_wait() {
            Ok(Some(_status)) => break,
            Ok(None) => {
                if Instant::now() >= cut {
                    let _ = kill(&mut child);
                    let _ = child.wait();
                    return (Run::Deadline, started.elapsed());
                }
                std::thread::sleep(Duration::from_millis(1));
            }
            Err(e) => {
                let _ = kill(&mut child);
                return (Run::Silent(format!("waiting on the driver child failed: {e}")), started.elapsed());
            }
        }
    }
    let Ok(output) = child.wait_with_output() else {
        return (Run::Silent("the driver child's pipes could not be read".into()), started.elapsed());
    };
    let stdout = String::from_utf8_lossy(&output.stdout);
    let answered = stdout
        .lines()
        .rev()
        .find(|line| line.starts_with('{'))
        .and_then(|line| serde_json::from_str::<serde_json::Value>(line).ok());
    match answered {
        Some(value) => (Run::Answered(value), started.elapsed()),
        None => {
            let exit = describe_exit(&output.status);
            let stderr = String::from_utf8_lossy(&output.stderr);
            let stderr = stderr.lines().rev().take(6).collect::<Vec<_>>().join(" | ");
            (Run::Silent(format!("{exit}; stderr: {}", tail(&stderr, 600))), started.elapsed())
        }
    }
}

#[cfg(unix)]
fn kill(child: &mut std::process::Child) -> std::io::Result<()> {
    // The child is its own process group leader (`process_group(0)`), so the signal reaches
    // anything the target spawned; the direct kill stays as the fallback.
    let group = child.id() as i32;
    let signalled = unsafe { libc_kill(-group, 9) };
    if signalled != 0 {
        return child.kill();
    }
    let _ = child.wait();
    Ok(())
}

#[cfg(not(unix))]
fn kill(child: &mut std::process::Child) -> std::io::Result<()> {
    child.kill()
}

#[cfg(unix)]
extern "C" {
    #[link_name = "kill"]
    fn libc_kill(pid: i32, sig: i32) -> i32;
}

#[cfg(unix)]
fn describe_exit(status: &std::process::ExitStatus) -> String {
    use std::os::unix::process::ExitStatusExt as _;
    match status.signal() {
        Some(signal) => format!("the driver child died on signal {signal}"),
        None => format!("the driver child exited with {}", status.code().unwrap_or(-1)),
    }
}

#[cfg(not(unix))]
fn describe_exit(status: &std::process::ExitStatus) -> String {
    format!("the driver child exited with {}", status.code().unwrap_or(-1))
}

/// Materialize one `ValueTree` into the JSON the generated code reads, shaped by the `Build`
/// tree. An `Err` here is the honest "the driver cannot build this value" answer `prepare`
/// skips on and `invoke` rejects with.
pub fn value_for(build: &Build, tree: &ValueTree) -> Result<serde_json::Value, String> {
    let node = &tree.node;
    Ok(match build {
        Build::Bool => match node {
            ValueNode::Boolean { value } => serde_json::json!(value),
            other => return Err(format!("{} is not a boolean", shape(other))),
        },
        Build::Int(t) => {
            let number = match node {
                ValueNode::Number { value } => value.as_f64(),
                ValueNode::BigInt { value } => match value.parse::<f64>() {
                    Ok(parsed) => parsed,
                    Err(_) => return Err(format!("{value} is not an integer")),
                },
                other => return Err(format!("{} is not a number", shape(other))),
            };
            if !number.is_finite() {
                return Err(format!("{number} is not a finite integer"));
            }
            if t.starts_with('u') {
                serde_json::json!(number as u64)
            } else {
                serde_json::json!(number as i64)
            }
        }
        Build::Float(_) => {
            let number = match node {
                ValueNode::Number { value } => value.as_f64(),
                ValueNode::BigInt { value } => match value.parse::<f64>() {
                    Ok(parsed) => parsed,
                    Err(_) => return Err(format!("{value} is not a number")),
                },
                other => return Err(format!("{} is not a number", shape(other))),
            };
            // JSON has no token for the non-finite values; the driver's `f_of` reads these names.
            if number.is_nan() {
                serde_json::json!("nan")
            } else if number == f64::INFINITY {
                serde_json::json!("infinity")
            } else if number == f64::NEG_INFINITY {
                serde_json::json!("negativeInfinity")
            } else {
                serde_json::json!(number)
            }
        }
        Build::Char => match node {
            ValueNode::String { value } => {
                let mut chars = value.chars();
                match (chars.next(), chars.next()) {
                    (Some(_), None) => serde_json::json!(value),
                    _ => return Err(format!("{value:?} is not one character")),
                }
            }
            other => return Err(format!("{} is not a string", shape(other))),
        },
        Build::Str | Build::PathBuf => match node {
            ValueNode::String { value } => serde_json::json!(value),
            other => return Err(format!("{} is not a string", shape(other))),
        },
        Build::JsonValue => json_passthrough(node)?,
        Build::Vec { inner } => {
            let out: Result<Vec<_>, _> = match node {
                ValueNode::Array { items } | ValueNode::Stream { items, .. } => items.iter().map(|item| value_for(inner, item)).collect(),
                ValueNode::Buffer { bytes } => bytes
                    .iter()
                    .map(|byte| value_for(inner, &ValueTree::new(ValueNode::number(*byte as f64))))
                    .collect(),
                other => return Err(format!("{} is not an array", shape(other))),
            };
            serde_json::json!(out?)
        }
        Build::Set { inner, ordered: _ } => {
            let items: &[ValueTree] = match node {
                ValueNode::Set { items } => items,
                ValueNode::Array { items } => items,
                other => return Err(format!("{} is not a set", shape(other))),
            };
            let out: Result<Vec<_>, _> = items.iter().map(|item| value_for(inner, item)).collect();
            serde_json::json!(out?)
        }
        Build::Map { value, ordered: _ } => {
            let entries: &[(ValueTree, ValueTree)] = match node {
                ValueNode::Map { entries } => entries,
                other => return Err(format!("{} is not a map", shape(other))),
            };
            let mut out = serde_json::Map::new();
            for (key, value_tree) in entries {
                let key = match &key.node {
                    ValueNode::String { value } => value.clone(),
                    other => return Err(format!("{} is not a string map key", shape(other))),
                };
                out.insert(key, value_for(value, value_tree)?);
            }
            serde_json::Value::Object(out)
        }
        Build::Tuple { items } => {
            let given: &[ValueTree] = match node {
                ValueNode::Tuple { items } => items,
                ValueNode::Array { items } => items,
                other => return Err(format!("{} is not a tuple", shape(other))),
            };
            if given.len() != items.len() {
                return Err(format!("a tuple of {} needs {} values, got {}", items.len(), items.len(), given.len()));
            }
            let out: Result<Vec<_>, _> = items.iter().zip(given).map(|(build, tree)| value_for(build, tree)).collect();
            serde_json::json!(out?)
        }
        Build::Option { inner } => {
            if matches!(node, ValueNode::Null | ValueNode::Undefined) {
                serde_json::Value::Null
            } else {
                value_for(inner, tree)?
            }
        }
        Build::Struct { fields, .. } => {
            let given: &[(String, ValueTree)] = match node {
                ValueNode::Object { fields } => fields,
                other => return Err(format!("{} is not an object", shape(other))),
            };
            let mut out = serde_json::Map::new();
            for (name, field_build) in fields {
                let Some((_, tree)) = given.iter().find(|(given, _)| given == name) else {
                    return Err(format!("the object has no field {name}"));
                };
                out.insert(name.clone(), value_for(field_build, tree)?);
            }
            serde_json::Value::Object(out)
        }
        Build::Enum { path, variants } => {
            match node {
                ValueNode::String { value } => {
                    if variants.iter().any(|v| v.name == *value && matches!(v.shape, crate::lower::VariantShape::Unit)) {
                        serde_json::json!(value)
                    } else {
                        return Err(format!("{value} is not a unit variant of {path}"));
                    }
                }
                ValueNode::Tuple { items } | ValueNode::Array { items } => {
                    let mut chosen: Option<serde_json::Value> = None;
                    for variant in variants {
                        if let crate::lower::VariantShape::Tuple(builds) = &variant.shape {
                            if builds.len() != items.len() {
                                continue;
                            }
                            let attempt: Result<Vec<_>, _> =
                                builds.iter().zip(items).map(|(build, tree)| value_for(build, tree)).collect();
                            if let Ok(values) = attempt {
                                chosen = Some(serde_json::json!(values));
                                break;
                            }
                        }
                    }
                    chosen.ok_or_else(|| format!("no tuple variant of {path} accepts the given array"))?
                }
                ValueNode::Object { fields } => {
                    let mut chosen: Option<serde_json::Value> = None;
                    for variant in variants {
                        if let crate::lower::VariantShape::Struct(builds) = &variant.shape {
                            let mut attempt = serde_json::Map::new();
                            let mut ok = true;
                            for (name, field_build) in builds {
                                match fields.iter().find(|(given, _)| given == name) {
                                    Some((_, tree)) => match value_for(field_build, tree) {
                                        Ok(value) => {
                                            attempt.insert(name.clone(), value);
                                        }
                                        Err(_) => {
                                            ok = false;
                                            break;
                                        }
                                    },
                                    None => {
                                        ok = false;
                                        break;
                                    }
                                }
                            }
                            if ok {
                                chosen = Some(serde_json::Value::Object(attempt));
                                break;
                            }
                        }
                    }
                    chosen.ok_or_else(|| format!("no struct variant of {path} accepts the given object"))?
                }
                other => return Err(format!("{} is not an enum value", shape(other))),
            }
        }
    })
}

/// Any JSON-shaped node becomes a `serde_json::Value` for a `serde_json::Value` parameter.
pub(crate) fn json_passthrough(node: &ValueNode) -> Result<serde_json::Value, String> {
    Ok(match node {
        ValueNode::Null | ValueNode::Undefined => serde_json::Value::Null,
        ValueNode::Boolean { value } => serde_json::json!(value),
        ValueNode::Number { value } => {
            let number = value.as_f64();
            if number.is_nan() {
                serde_json::json!("nan")
            } else if number == f64::INFINITY {
                serde_json::json!("infinity")
            } else if number == f64::NEG_INFINITY {
                serde_json::json!("negativeInfinity")
            } else {
                serde_json::json!(number)
            }
        }
        ValueNode::BigInt { value } => value.parse::<i64>().map(|n| serde_json::json!(n)).unwrap_or_else(|_| serde_json::json!(value)),
        ValueNode::String { value } => serde_json::json!(value),
        ValueNode::Literal { value } => value.clone(),
        ValueNode::Array { items } | ValueNode::Set { items } | ValueNode::Tuple { items } | ValueNode::Stream { items, .. } => {
            serde_json::Value::Array(items.iter().map(|item| json_passthrough(&item.node)).collect::<Result<_, _>>()?)
        }
        ValueNode::Buffer { bytes } => serde_json::json!(bytes),
        ValueNode::Map { entries } => {
            let mut out = serde_json::Map::new();
            for (key, value) in entries {
                let key = match &key.node {
                    ValueNode::String { value } => value.clone(),
                    other => return Err(format!("{} is not a string map key", shape(other))),
                };
                out.insert(key, json_passthrough(&value.node)?);
            }
            serde_json::Value::Object(out)
        }
        ValueNode::Object { fields } => {
            let mut out = serde_json::Map::new();
            for (name, value) in fields {
                out.insert(name.clone(), json_passthrough(&value.node)?);
            }
            serde_json::Value::Object(out)
        }
        ValueNode::Function { .. } => return Err("a function stub has no JSON representation".into()),
        ValueNode::Opaque { ty } => return Err(format!("{ty} must be supplied by a fixture")),
    })
}

fn shape(node: &ValueNode) -> &'static str {
    match node {
        ValueNode::Null => "null",
        ValueNode::Undefined => "undefined",
        ValueNode::Boolean { .. } => "a boolean",
        ValueNode::Number { .. } => "a number",
        ValueNode::BigInt { .. } => "a big integer",
        ValueNode::String { .. } => "a string",
        ValueNode::Literal { .. } => "a literal",
        ValueNode::Array { .. } => "an array",
        ValueNode::Set { .. } => "a set",
        ValueNode::Map { .. } => "a map",
        ValueNode::Object { .. } => "an object",
        ValueNode::Tuple { .. } => "a tuple",
        ValueNode::Buffer { .. } => "a buffer",
        ValueNode::Function { .. } => "a function stub",
        ValueNode::Stream { .. } => "a stream",
        ValueNode::Opaque { .. } => "an opaque value",
    }
}

/// One line describing the call for `MaterializedCall.summary`.
pub fn summarize(tgt: &Tgt, values: &[ValueTree]) -> String {
    let mut parts: Vec<String> = Vec::new();
    for (param, value) in tgt.params.iter().zip(values) {
        parts.push(summarize_tree(&param.build, value));
        if parts.join(", ").len() > 160 {
            parts.push("…".into());
            break;
        }
    }
    format!("{}({})", tgt.name, parts.join(", "))
}

fn summarize_tree(build: &Build, tree: &ValueTree) -> String {
    match (&tree.node, build) {
        (ValueNode::Object { fields }, Build::Struct { .. }) => {
            format!("{{ {} }}", fields.iter().map(|(n, v)| format!("{n}: {}", summarize_shallow(v))).collect::<Vec<_>>().join(", "))
        }
        (ValueNode::Array { items }, _) | (ValueNode::Set { items }, _) | (ValueNode::Tuple { items }, _) => {
            format!("[{}]", items.iter().take(4).map(summarize_shallow).collect::<Vec<_>>().join(", "))
        }
        (node, _) => summarize_shallow(&ValueTree { node: node.clone(), provenance: Default::default() }),
    }
}

fn summarize_shallow(tree: &ValueTree) -> String {
    match &tree.node {
        ValueNode::String { value } => {
            let mut short = value.clone();
            if short.len() > 40 {
                short.truncate(40);
                short.push('…');
            }
            format!("{short:?}")
        }
        other => shape(other).to_string(),
    }
}

